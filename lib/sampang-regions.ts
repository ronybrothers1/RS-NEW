export type SampangSubdistrict =
  (typeof SAMPANG_REGIONS)[number]["subdistrict"];

export function getSampangVillages(
  subdistrict: string,
): readonly string[] {
  const region =
    SAMPANG_REGIONS.find(
      (item) =>
        item.subdistrict ===
        subdistrict,
    );

  return region?.villages || [];
}

export function isValidSampangSubdistrict(
  value: string,
) {
  return SAMPANG_REGIONS.some(
    (item) =>
      item.subdistrict ===
      value,
  );
}

export function isValidSampangVillage(
  subdistrict: string,
  village: string,
) {
  return getSampangVillages(
    subdistrict,
  ).some(
    (item) =>
      item === village,
  );
}
